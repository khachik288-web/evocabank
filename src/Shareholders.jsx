function AccordionItem({ title, children }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="mb-3 overflow-hidden rounded-2xl border border-purple-200 bg-white">
      <button
        type="button"
        onClick={() => setOpen((o) => !o)}
        className="flex w-full items-center gap-4 px-5 py-4 text-left"
        aria-expanded={open}
      >
        <Chevron open={open} />
        <span className="text-[15px] font-semibold text-gray-500">{title}</span>
      </button>
      {open && <div className="border-t border-purple-100 px-6 py-5 text-[15px] leading-relaxed text-gray-700">{children}</div>}
    </div>
  );
}

