/* ---------------------------------------------------------------
   Разметка текста: **жирный** + автоссылки (http(s):// и www.)
---------------------------------------------------------------- */
const URL_RE = /((?:https?:\/\/|www\.)[A-Za-z0-9./_\-?=&%#]+)/g;

function linkify(text, keyPrefix) {
  return text.split(URL_RE).map((part, i) => {
    if (i % 2 === 1) {
      const href = part.startsWith('http') ? part : `https://${part}`;
      return (
        <a key={`${keyPrefix}-${i}`} href={href} target="_blank" rel="noreferrer"
           className="underline" style={{ color: PURPLE }}>
          {part}
        </a>
      );
    }
    return part;
  });
}

function Italic({ text, k }) {
  return text.split('~~').map((seg, i) =>
    i % 2 === 1 ? <em key={`${k}-${i}`}>{linkify(seg, `${k}-${i}`)}</em> : <React.Fragment key={`${k}-${i}`}>{linkify(seg, `${k}-${i}`)}</React.Fragment>
  );
}

function Inline({ text }) {
  return text.split('**').map((seg, i) =>
    i % 2 === 1 ? <strong key={i}><Italic text={seg} k={i} /></strong> : <Italic key={i} text={seg} k={i} />
  );
}

/* ---------------------------------------------------------------
   Таблицы
---------------------------------------------------------------- */
function DataTable({ head, rows, caption, numbered = true, widths }) {
  const cell = 'border border-[#ead9ff] px-3.5 py-3 align-middle text-[13px] leading-6';
  const renderCell = (c) => {
    const lines = Array.isArray(c) ? c : [c];
    return lines.map((l, i) => (
      <React.Fragment key={i}>
        {/^[\w.-]+@[\w.-]+$/.test(l) ? (
          <a href={`mailto:${l}`} className="font-medium underline" style={{ color: PURPLE }}>{l}</a>
        ) : (
          l
        )}
        {i < lines.length - 1 && <br />}
      </React.Fragment>
    ));
  };
  return (
    <div className="my-8">
      {caption && <p className="mb-4 text-center text-[15px] font-bold">{caption}</p>}
      <div className="overflow-x-auto rounded-lg shadow-[0_2px_12px_rgba(106,0,219,0.12)]">
        <table className="w-full border-collapse bg-white">
          <thead>
            <tr>
              {numbered && <th className={`${cell} w-12`} />}
              {head.map((h, i) => (
                <th key={i} className={`${cell} text-left font-bold`} style={widths ? { width: widths[i] } : undefined}>{h}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map((r, ri) => (
              <tr key={ri}>
                {numbered && <td className={cell}>{ri + 1}</td>}
                {r.map((c, ci) => (
                  <td key={ci} className={`${cell} ${ci === 0 && numbered ? 'font-bold' : ''}`}>{renderCell(c)}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

/* ---------------------------------------------------------------
   Рендер блоков контента
---------------------------------------------------------------- */
function Blocks({ blocks }) {
  return blocks.map((b, i) => {
    const [type, val, extra] = b;
    switch (type) {
      case 'h2':
        return <h2 key={i} className="mb-5 mt-14 text-[34px] font-normal leading-tight text-[#2b2b2b]">{val}</h2>;
      case 'q':
        return (
          <div key={i} className="mb-6 mt-8 flex items-start gap-4 pl-5">
            <span className="mt-[11px] h-2.5 w-2.5 flex-none rounded-full" style={{ background: PURPLE }} />
            <strong className="text-[16px] leading-7">{val}</strong>
          </div>
        );
      case 'b':
        return <p key={i} className="mb-3 mt-6 text-[15px] font-bold leading-7"><Inline text={val} /></p>;
      case 'p':
        return <p key={i} className="mb-5 text-[16px] leading-7 text-[#222]"><Inline text={val} /></p>;
      case 'ind':
        return <p key={i} className="mb-3 pl-5 text-[16px] leading-7 text-[#222]"><Inline text={val} /></p>;
      case 'ul':
        return (
          <ul key={i} className="mb-6 list-none space-y-3 pl-5">
            {val.map((it, j) => (
              <li key={j} className="flex items-start gap-4 text-[16px] leading-7 text-[#222]">
                <span className="mt-[11px] h-2.5 w-2.5 flex-none rounded-full" style={{ background: PURPLE }} />
                <span><Inline text={it} /></span>
              </li>
            ))}
          </ul>
        );
      case 'img':
        return (
          <div key={i} className="my-6 overflow-x-auto pl-5">
            <img src={FORMULA(val)} alt={extra || 'formula'} loading="lazy" className="max-w-full" />
          </div>
        );
      case 'table':
        return <DataTable key={i} {...val} />;
      default:
        return null;
    }
  });
}

